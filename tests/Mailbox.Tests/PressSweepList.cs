using System.Text;
using Mailbox.Core.Commands;

namespace Mailbox.Tests;

/// <summary>
/// Writes the press sweep's pose list from the registered catalogue itself. Skipped in an
/// ordinary run; set <c>MAILBOX_PRESS_LIST</c> to a path to produce one.
/// </summary>
/// <remarks>
/// The sweep's question is the owner's: which buttons, pressed, do nothing? The static sweeps
/// prove every command is described and chorded; the enablement tests prove the declarations are
/// consistent; nothing presses them. This list makes <c>tools/audit-run.sh</c> do exactly that —
/// one pose per command, in the module the command belongs to, with a selection posed and the
/// clock pinned, each classified afterwards from the settled read-back the run door logs.
/// <para>
/// The list is generated rather than written, so a command added to the catalogue is in the
/// sweep the next time it runs, and a set added to the application fails the coverage assertion
/// below rather than going quietly unswept. The three item-window sets — compose, contact,
/// appointment — are swept through their windows' own doors: the shell's press opens the
/// window over a seeded item, and the window's door presses inside it.
/// </para>
/// </remarks>
public class PressSweepList
{
    /// <summary>The sets the shell's dispatcher reaches, with the module each is pressed in.</summary>
    private static readonly (string Module, IEnumerable<MailboxCommand> Commands, string Name)[] Swept =
    [
        ("mail", MailCommands.All, nameof(MailCommands)),
        ("mail", ViewCommands.All, nameof(ViewCommands)),
        ("calendar", CalendarCommands.All, nameof(CalendarCommands)),
        ("people", PeopleCommands.All, nameof(PeopleCommands)),
        ("tasks", TaskCommands.All, nameof(TaskCommands)),
        ("notes", NoteCommands.All, nameof(NoteCommands)),
        ("journal", JournalCommands.All, nameof(JournalCommands)),
        ("feeds", FeedCommands.All, nameof(FeedCommands)),
    ];

    /// <summary>The item windows' sets, each swept through its window's own door rather than the shell's.</summary>
    private static readonly string[] WindowSwept =
        [nameof(ComposeCommands), nameof(ContactCommands), nameof(AppointmentCommands)];

    /// <summary>
    /// The two subscriptions whose folders <c>SeedHarness.SeedFeedsStore</c> builds, as the
    /// settings JSON the pose injects — names and categories must match the seeded tree or the
    /// workspace maps them to nothing.
    /// </summary>
    private const string SeededSubscriptions =
        "[{\"url\":\"https://example.invalid/ars\",\"name\":\"Ars Technica\",\"category\":\"Technology\"},"
        + "{\"url\":\"https://example.invalid/bbc\",\"name\":\"BBC News\",\"category\":\"News\"}]";

    /// <summary>
    /// Every command set the assembly declares is swept — through a module or through an item
    /// window's own door. A new set cannot go quietly unswept.
    /// </summary>
    [Fact]
    public void EveryCommandSetIsSwept()
    {
        var declared = typeof(MailCommands).Assembly.GetTypes()
            .Where(t => t is { IsAbstract: true, IsSealed: true }
                        && t.Namespace == typeof(MailCommands).Namespace
                        && t.Name.EndsWith("Commands", StringComparison.Ordinal))
            .Select(t => t.Name)
            .OrderBy(n => n, StringComparer.Ordinal)
            .ToList();

        var covered = Swept.Select(s => s.Name).Concat(WindowSwept)
            .OrderBy(n => n, StringComparer.Ordinal)
            .ToList();

        Assert.Equal(declared, covered);
    }

    [Fact]
    public void WriteOnRequest()
    {
        if (Environment.GetEnvironmentVariable("MAILBOX_PRESS_LIST") is not { Length: > 0 } path) return;

        var list = new StringBuilder();
        list.AppendLine("# The press sweep: one pose per command in the catalogue, generated by");
        list.AppendLine("# PressSweepList.WriteOnRequest — regenerate rather than edit. Item-window");
        list.AppendLine("# commands are pressed inside their own windows, opened by the shell's press.");

        foreach (var (module, commands, _) in Swept)
        {
            foreach (var command in commands)
            {
                // Tab-separated pairs, which is the runner's format for a value carrying a
                // space — the feeds subscriptions carry several. wait-1500 lets the posed
                // module switch and selection land first; the press itself then reports the
                // settled read-back the classifier reads.
                // Every module's selection door names a seeded item of its own, so a command
                // that acts on the selection has one to act on; the guard poses below are
                // where the refusals stay proven.
                var select = module switch
                {
                    "people" => "A. Person",
                    "calendar" => "Dentist",
                    "tasks" => "Book the meeting room",
                    "notes" => "Shopping",
                    "journal" => "Sent the agenda round",
                    "feeds" => "fsync",
                    _ => "1",
                };

                var pairs = new List<string>
                {
                    $"MAILBOX_MODULE={module}",
                    $"MAILBOX_SELECT={select}",
                    "MAILBOX_TODAY=2026-08-16",
                };

                // The feeds poses carry the two subscriptions whose folders the seed builds,
                // so the module opens onto articles rather than an empty pane.
                if (module == "feeds") pairs.Add($"MAILBOX_SETTING=rss.feeds={SeededSubscriptions}");

                pairs.Add($"MAILBOX_RUN=wait-1500,{command.Id.Value}");

                list.AppendLine($"press-{command.Id.Value}\t" + string.Join('\t', pairs));
            }
        }

        // The compose window's commands, each pressed in its own posed window through the same
        // entry point the window's ribbon uses. The body is posed and then selected — through
        // the door itself — so a formatting or editing press has something to act on; each
        // press logs the settled line the classifier reads.
        foreach (var command in ComposeCommands.All.Where(c => c.Surface == CommandSurface.Compose))
        {
            list.AppendLine(
                $"press-{command.Id.Value}"
                + "\tMAILBOX_COMPOSE=1"
                + "\tMAILBOX_COMPOSE_BODY=The quick brown fox."
                + "\tMAILBOX_TODAY=2026-08-16"
                + $"\tMAILBOX_COMPOSE_RUN=format.selectall,{command.Id.Value}");
        }

        // The contact window's commands — and the ten Contact-surface inserts filed in the
        // compose class, since this window is where those buttons actually live. The shell's
        // own press opens the window over the seeded person; the window's door presses inside
        // it and logs the settled line.
        foreach (var command in ContactCommands.All
                     .Concat(ComposeCommands.All.Where(c => c.Surface == CommandSurface.Contact)))
        {
            list.AppendLine(
                $"press-{command.Id.Value}"
                + "\tMAILBOX_MODULE=people"
                + "\tMAILBOX_SELECT=A. Person"
                + "\tMAILBOX_TODAY=2026-08-16"
                + "\tMAILBOX_RUN=wait-1500,people.open"
                + $"\tMAILBOX_CONTACT_RUN={command.Id.Value}");
        }

        // The appointment window's commands, over the seeded appointment the calendar door
        // selects and the shell's press opens.
        foreach (var command in AppointmentCommands.All)
        {
            list.AppendLine(
                $"press-{command.Id.Value}"
                + "\tMAILBOX_MODULE=calendar"
                + "\tMAILBOX_SELECT=Dentist"
                + "\tMAILBOX_TODAY=2026-08-16"
                + "\tMAILBOX_RUN=wait-1500,calendar.item.open"
                + $"\tMAILBOX_APPOINTMENT_RUN={command.Id.Value}");
        }

        // The guards, kept: one press per module with no selection posed at all, named
        // <id>~guard so the classifier reads the same command through a different door. A
        // selection door that quietly began inventing a selection would show here as a class
        // change on the guard row.
        foreach (var (module, id) in new[]
        {
            ("calendar", "calendar.item.open"),
            ("tasks", "tasks.private"),
            ("notes", "notes.categorize"),
            ("journal", "journal.categorize"),
            ("feeds", "feeds.readlater"),
        })
        {
            list.AppendLine(
                $"press-{id}~guard\tMAILBOX_MODULE={module}\tMAILBOX_TODAY=2026-08-16\tMAILBOX_RUN=wait-1500,{id}");
        }

        File.WriteAllText(path, list.ToString());
    }
}
